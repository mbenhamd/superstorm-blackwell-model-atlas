/**
 * Imports external published benchmark results (concurrency ladders and single points from third parties, engine
 * projects and vendors, each with an engine-version audit) into data/external-benchmarks.json, and regenerates the
 * external source table in docs/SOURCES.md.
 *
 *   bun scripts/import-external.ts <merged.json>     # transform, validate, write both files
 *   bun scripts/import-external.ts --check [<merged.json>]
 *
 * The source is a research export (`ladders`, `points`, `sources`, `releases`, `conventions`); pass its path or set
 * EXTERNAL_SOURCE. `--check` validates the committed file (schema, unique ids, sources, catalog model and
 * configuration ids, labelled flags, no local paths), verifies it is in canonical form and that docs/SOURCES.md is in
 * sync, and, when a source is given, that regenerating from it changes nothing. Pipeline bookkeeping (merge origins,
 * working file names, research gaps) is not imported; local file paths inside notes are removed. Records keep the
 * source's metric names, units and values; nothing is converted, filled or ranked.
 */
import { join } from "node:path";
import atlas from "../src/data/atlas.json";
import { EXTERNAL_SCHEMA_VERSION, gpuTypeStated, parseExternalDataset, type ExternalCatalogRefs } from "../src/domain/external.js";

const root = join(import.meta.dir, "..");
const OUT = join(root, "data/external-benchmarks.json");
const SOURCES_DOC = join(root, "docs/SOURCES.md");
const START = "<!-- external-sources:start (generated by scripts/import-external.ts; do not edit) -->";
const END = "<!-- external-sources:end -->";

type Json = Record<string, unknown>;
const isObject = (value: unknown): value is Json => typeof value === "object" && value !== null && !Array.isArray(value);

export const catalogRefs: ExternalCatalogRefs = {
  modelIds: new Set(atlas.models.map((model) => model.id)),
  configurationModels: new Map(atlas.configurations.map((config) => [config.id, config.modelId])),
};

/**
 * Descriptions for caveat flags the research export uses without a convention entry (point records and a combined
 * key). Worded from how the export applies them; the export's own descriptions take precedence.
 */
const FLAG_DESCRIPTIONS: Record<string, string> = {
  "engine-version-not-stated": "the source states no engine build identity",
  "custom-image-tag": "engine is a named non-release image or custom build",
  "pre-release-engine-build": "engine is a nightly, dev or release-candidate build, not a stable release",
  "artifact-or-revision-differs": "published checkpoint or revision differs from, or cannot be tied to, the catalog artifact",
  "throughput-includes-cached-input": "throughput counts prefix-cache-hit input tokens",
  "kv-offload-host-dram": "KV cache offloaded to host memory",
  "low-provenance": "configuration, checkpoint or harness only partly stated by the source",
  "multi-node": "deployment spans more than one node",
  "multi-replica": "figure aggregates more than one serving replica",
  "relative-only": "the source publishes a relative figure only (speedup), not an absolute rate",
  "not-a-throughput-measurement": "the published figure is not a throughput measurement (e.g. memory capacity)",
  "orchestrated-or-other-engine": "served through an orchestrator or an engine other than vLLM/SGLang",
  "gpu-type-unstated": "GPU type not stated by the source",
};

/** Removes local working-file references from free text (the export cites its extraction files in some notes). */
export function scrub(text: string): string {
  return text
    .replace(/\s*\(compact metrics; full metrics in \/tmp\/[^)]*\)/g, " (compact metrics)")
    .replace(/(?:\/tmp|\/Users|\/home|\/var\/folders|\/private)\/[^\s;,)'"]+/g, "(local extraction file, not published)");
}
const clean = (value: unknown): string | null => (typeof value === "string" ? scrub(value) : null);
const num = (value: unknown): number | null => (typeof value === "number" && Number.isFinite(value) ? value : null);

function metricKey(metric: Json): string {
  return JSON.stringify([metric.name, metric.unit ?? null, metric.perGpu === true, metric.percentile ?? null, metric.publishedLabel ?? null, metric.note ?? null]);
}

/** Published metrics of one record as shared columns plus one value row per level (lossless; cell objects keep ranges, bounds and denominators). */
function columns(levels: { base: Json; metrics: Json[] }[]): { metrics: unknown[]; levels: Json[] } {
  const index = new Map<string, number>();
  const metrics: unknown[] = [];
  for (const level of levels) for (const metric of level.metrics) {
    const key = metricKey(metric);
    if (index.has(key)) continue;
    index.set(key, metrics.length);
    // [name, unit, perGpu, percentile, label?, note?]: the source label and the derivation note only when recorded.
    const tuple: unknown[] = [clean(metric.name), metric.unit ?? null, metric.perGpu === true, metric.percentile ?? null];
    if (metric.publishedLabel || metric.note) tuple.push(clean(metric.publishedLabel));
    if (metric.note) tuple.push(clean(metric.note));
    metrics.push(tuple as unknown as Json);
  }
  const rows = levels.map((level) => {
    const values: unknown[] = Array(metrics.length).fill(null);
    for (const metric of level.metrics) {
      const detail = { ...(Array.isArray(metric.range) ? { range: metric.range } : {}), ...(num(metric.valueMax) !== null ? { valueMax: metric.valueMax } : {}), ...(num(metric.of) !== null ? { of: metric.of } : {}), ...(typeof metric.qualifier === "string" ? { qualifier: metric.qualifier } : {}) };
      values[index.get(metricKey(metric))!] = Object.keys(detail).length ? { value: num(metric.value), ...detail } : num(metric.value);
    }
    return { ...level.base, values };
  });
  return { metrics, levels: rows };
}

function audit(input: unknown): Json {
  const a = isObject(input) ? input : {};
  // raw is the record's engineVersion and is not repeated; absent fields read as null.
  return compact({
    class: a.class, canonical: clean(a.canonical), releaseDate: a.releaseDate ?? null, availableFrom: a.availableFrom ?? null,
    engineFamily: a.engineFamily ?? null, baseRelease: clean(a.baseRelease), flags: Array.isArray(a.flags) && a.flags.length ? a.flags.map((flag) => scrub(String(flag))) : null,
    sourceText: clean(a.sourceText),
  });
}

/** Drops null fields (the parser reads an absent optional field as null). */
const compact = (object: Json, keep: readonly string[] = []): Json => Object.fromEntries(Object.entries(object).filter(([key, value]) => value !== null || keep.includes(key)));

const LEVEL_SKIP = new Set(["metrics", "concurrency", "requestRate"]);
function levelExtras(level: Json): Json {
  return Object.fromEntries(Object.entries(level).filter(([key, value]) => !LEVEL_SKIP.has(key) && value !== null && value !== undefined).map(([key, value]) => [key, typeof value === "string" ? scrub(value) : value]));
}

function record(input: Json, kind: "ladder" | "point"): Json {
  const levels = kind === "ladder"
    ? (input.levels as Json[]).map((level) => ({ base: compact({ concurrency: num(level.concurrency), requestRate: num(level.requestRate), ...levelExtras(level) }, ["concurrency"]), metrics: level.metrics as Json[] }))
    : [(() => {
      const load = input.loadPoint;
      const base: Json = typeof load === "string"
        ? { concurrency: null, label: scrub(load) }
        : compact({ concurrency: num((load as Json)?.concurrency), requestRate: num((load as Json)?.requestRate), ...Object.fromEntries(Object.entries((load as Json) ?? {}).filter(([key, value]) => key !== "concurrency" && key !== "requestRate" && value !== null).map(([key, value]) => [key, typeof value === "string" ? scrub(value) : value])) }, ["concurrency"]);
      return { base, metrics: input.metrics as Json[] };
    })()];
  const workload = isObject(input.workload) ? input.workload : {};
  const correction = typeof input.verifierCorrection === "string" ? { note: scrub(input.verifierCorrection), fields: Array.isArray(input.verifierCorrectionApplied) ? input.verifierCorrectionApplied : [] } : null;
  // A GPU type the source does not state is unknown, not a mismatch: no gpuType, "gpu-type-unstated" instead of
  // "hardware-mismatch" / "other-hardware" (rendered "not B300" / "other GPU", kept for a stated non-B300 GPU).
  const gpuType = typeof input.gpuType === "string" && gpuTypeStated(input.gpuType) ? input.gpuType : null;
  const rawFlags = (Array.isArray(input.flags) ? input.flags : []).map(String);
  const flags = [...new Set(gpuType === null ? [...rawFlags.filter((flag) => flag !== "hardware-mismatch" && flag !== "other-hardware"), "gpu-type-unstated"] : rawFlags)].sort();
  return compact({
    id: input.id, kind, modelId: input.modelId,
    publishedModel: clean(input.publishedModel), precision: clean(input.precision), gpuType, gpuCount: num(input.gpuCount),
    topology: clean(input.topology), hardware: clean(input.hardware),
    engine: clean(input.engine), engineVersion: clean(input.engineVersion), audit: audit(input.engineVersionAudit), config: clean(input.config),
    workload: { name: clean(workload.name), isl: num(workload.isl), osl: num(workload.osl) },
    sourceId: input.sourceId, publishedOn: input.publishedOn ?? null, evidenceClass: clean(input.evidenceClass),
    catalogConfigurationId: input.catalogConfigurationId ?? null, closestCatalogConfigurationId: input.closestCatalogConfigurationId ?? null,
    mismatch: clean(input.mismatch), flags, notes: clean(input.notes), correction,
    ...columns(levels),
  }, ["catalogConfigurationId", "gpuType", "gpuCount", "precision"]);
}

/** The repository form of a research export: deterministic order, referenced sources only, no pipeline bookkeeping. */
export function transform(merged: unknown): Json {
  if (!isObject(merged) || !Array.isArray(merged.ladders) || !Array.isArray(merged.points) || !isObject(merged.sources) || !isObject(merged.conventions)) {
    throw new Error("The source must be a research export with ladders, points, sources and conventions");
  }
  const records = [...(merged.ladders as Json[]).map((item) => record(item, "ladder")), ...(merged.points as Json[]).map((item) => record(item, "point"))]
    .sort((a, b) => String(a.modelId).localeCompare(String(b.modelId)) || String(a.id).localeCompare(String(b.id)));
  const used = new Set(records.map((item) => item.sourceId as string));
  const sources = Object.fromEntries(Object.keys(merged.sources).filter((id) => used.has(id)).sort().map((id) => {
    const s = (merged.sources as Json)[id] as Json;
    const extra = [s.note, s.pr ? `PR ${s.pr}` : null, s.recipe ? `Recipe ${s.recipe}` : null, Array.isArray(s.fragments) && s.fragments.length ? `Also ${s.fragments.join(", ")}` : null].filter(Boolean).map((item) => scrub(String(item)));
    return [id, {
      url: s.url, title: clean(s.title), publisher: clean(s.publisher), publishedOn: s.publishedOn ?? null, evidenceClass: clean(s.evidenceClass), retrievedOn: s.retrievedOn ?? null,
      ...(s.apiUrl ? { apiUrl: s.apiUrl } : {}), ...(s.run ? { run: s.run } : {}), ...(extra.length ? { note: extra.join("; ") } : {}),
      ...(s.dateNote ? { dateNote: clean(s.dateNote) } : {}), ...(Array.isArray(s.aliases) && s.aliases.length ? { aliases: [...s.aliases].sort() } : {}),
    }];
  }));
  const conventions = merged.conventions as Json;
  const exported = Object.entries(isObject(conventions.flags) ? conventions.flags : {}).filter(([key]) => !key.includes(" / "));
  const usedFlags = new Set(records.flatMap((item) => item.flags as string[]));
  const flags = Object.fromEntries([...new Map([...Object.entries(FLAG_DESCRIPTIONS), ...exported.map(([key, value]) => [key, scrub(String(value))] as [string, string])])]
    .filter(([key]) => usedFlags.has(key)).sort(([a], [b]) => a.localeCompare(b)));
  const releases = Object.fromEntries(Object.entries(isObject(merged.releases) ? merged.releases : {}).sort(([a], [b]) => a.localeCompare(b)).map(([engine, list]) => [engine,
    (Array.isArray(list) ? list as Json[] : []).map((item) => ({ version: item.version, date: item.date ?? null, prerelease: item.prerelease === true }))
      .sort((a, b) => String(b.date).localeCompare(String(a.date)) || String(a.version).localeCompare(String(b.version)))]));
  return {
    $comment: "External published results (third-party, engine-project and vendor benchmarks), evidence class \"external\". Not measured by this console, not KServe measurements, and never used for ranking, sustainable throughput, C_max, Δ vs best, champions, frontier or Compare deltas. Generated by scripts/import-external.ts; do not edit by hand.",
    schemaVersion: EXTERNAL_SCHEMA_VERSION,
    retrievedOn: merged.retrievedOn,
    conventions: {
      flags,
      derived: scrub(String(conventions.derived)),
      kserve: scrub(String(conventions.kserve)),
      versionClasses: isObject(conventions.engineVersionAudit) ? Object.fromEntries(Object.entries(conventions.engineVersionAudit).map(([key, value]) => [key, scrub(String(value))])) : {},
    },
    releases, sources, records,
  };
}

/* Readable, diff-friendly serialisation: structure on separate lines, each source / metric / level on one line. */
const EXPANDED = [/^$/, /^\.conventions$/, /^\.conventions\.(flags|versionClasses)$/, /^\.releases$/, /^\.releases\.[^.[\]]+$/, /^\.sources$/, /^\.records$/, /^\.records\[\]$/, /^\.records\[\]\.(metrics|levels)$/];
function format(value: unknown, path = "", indent = ""): string {
  if (!EXPANDED.some((pattern) => pattern.test(path)) || value === null || typeof value !== "object") return JSON.stringify(value);
  const inner = `${indent}  `;
  if (Array.isArray(value)) return value.length ? `[\n${value.map((item) => `${inner}${format(item, `${path}[]`, inner)}`).join(",\n")}\n${indent}]` : "[]";
  const entries = Object.entries(value as Json);
  return entries.length ? `{\n${entries.map(([key, item]) => `${inner}${JSON.stringify(key)}: ${format(item, `${path}.${key}`, inner)}`).join(",\n")}\n${indent}}` : "{}";
}
export const serialise = (file: Json): string => `${format(file)}\n`;

const cell = (text: string): string => text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
/** Markdown table of the external sources (generated section of docs/SOURCES.md). */
export function sourcesSection(file: Json): string {
  const sources = Object.entries(file.sources as Record<string, Json>);
  const records = file.records as Json[];
  const count = (id: string) => records.filter((item) => item.sourceId === id).length;
  const rows = sources.sort(([, a], [, b]) => String(a.publisher).localeCompare(String(b.publisher)) || String(a.title).localeCompare(String(b.title)))
    .map(([id, s]) => `| ${cell(String(s.publisher))} | [${cell(String(s.title))}](${s.url}) | ${s.publishedOn && s.publishedOn !== "not stated" ? s.publishedOn : "not stated"} | ${cell(String(s.evidenceClass))} | ${count(id)} | \`${id}\` |`);
  return [
    START,
    "",
    `### External published results (${sources.length} sources, ${records.length} records, retrieved ${file.retrievedOn})`,
    "",
    "Evidence class \"external\": published by the listed third parties, engine projects and vendors on their own serving stacks. Shown with source, date, hardware, engine version audit class and caveat flags; never ranked against or mixed with measured runs. Data: `data/external-benchmarks.json`.",
    "",
    "| Publisher | Source | Published | Evidence (as classified) | Records | ID |",
    "| --- | --- | --- | --- | ---: | --- |",
    ...rows,
    "",
    END,
  ].join("\n");
}
export function withSourcesSection(doc: string, section: string): string {
  const start = doc.indexOf(START), end = doc.indexOf(END);
  if (start >= 0 && end > start) return `${doc.slice(0, start)}${section}${doc.slice(end + END.length)}`;
  return `${doc.trimEnd()}\n\n${section}\n`;
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const sourcePath = args.find((arg) => !arg.startsWith("--")) ?? process.env.EXTERNAL_SOURCE ?? null;
  const doc = await Bun.file(SOURCES_DOC).text();
  if (check) {
    const text = await Bun.file(OUT).text();
    const committed = JSON.parse(text) as Json;
    const dataset = parseExternalDataset(committed, catalogRefs);
    const problems: string[] = [];
    if (serialise(committed) !== text) problems.push("data/external-benchmarks.json is not in canonical form (re-run the import)");
    if (withSourcesSection(doc, sourcesSection(committed)) !== doc) problems.push("docs/SOURCES.md external source table is out of date (re-run the import)");
    if (sourcePath) {
      const regenerated = serialise(transform(await Bun.file(sourcePath).json()));
      if (regenerated !== text) problems.push(`data/external-benchmarks.json differs from a fresh import of ${sourcePath.split("/").pop()}`);
    }
    if (problems.length) { for (const problem of problems) console.error(problem); process.exit(1); }
    console.log(`data/external-benchmarks.json valid: ${dataset.records.length} records (${dataset.records.filter((r) => r.kind === "ladder").length} ladders), ${Object.keys(dataset.sources).length} sources${sourcePath ? ", matches the source" : " (no source given: regeneration not compared)"}`);
    return;
  }
  if (!sourcePath) throw new Error("Usage: bun scripts/import-external.ts <research-export.json> [--check] (or set EXTERNAL_SOURCE)");
  const file = transform(await Bun.file(sourcePath).json());
  const dataset = parseExternalDataset(file, catalogRefs);
  const text = serialise(file);
  await Bun.write(OUT, text);
  await Bun.write(SOURCES_DOC, withSourcesSection(doc, sourcesSection(file)));
  const kib = (bytes: number) => (bytes / 1024).toFixed(1);
  const minified = JSON.stringify(file);
  console.log(`Wrote data/external-benchmarks.json: ${dataset.records.length} records, ${Object.keys(dataset.sources).length} sources; ${kib(text.length)} KiB on disk, ${kib(minified.length)} KiB minified, ${kib(Bun.gzipSync(minified).length)} KiB gzip`);
}

if (import.meta.main) await main();
